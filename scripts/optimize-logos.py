"""Regenerate responsive logos. Requires Pillow 12.3.0; originals stay untouched."""
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / 'src/assets/logos'
OUTPUT = SOURCES / 'optimized'
NAMES = ['capital_dance', 'capital', 'heart_uk', 'radio_X', 'pr_chicago',
         'polish_radio_london', 'radio_bielsko', 'radio_eska', 'rmf_maxx']
SIZES = [96, 192, 384]
OUTPUT.mkdir(exist_ok=True)
imports, entries = [], []
for index, name in enumerate(NAMES):
    with Image.open(SOURCES / f'{name}.png') as source:
        image = ImageOps.exif_transpose(source).convert('RGBA')
        for size in SIZES:
            resized = ImageOps.pad(image, (size, size), method=Image.Resampling.LANCZOS,
                                   color=(0, 0, 0, 0))
            target = OUTPUT / f'{name}-{size}.webp'
            resized.save(target, 'WEBP', quality=82, method=6, exact=True)
            imports.append(f"import logo{index}_{size} from '../assets/logos/optimized/{target.name}';")
    srcset = ', '.join(f'${{logo{index}_{size}}} {size}w' for size in SIZES)
    artwork = ', '.join(f"{{ src: logo{index}_{size}, sizes: '{size}x{size}', type: 'image/webp' }}" for size in SIZES)
    entries.append(f"  '{name}': {{ logo: logo{index}_192, logoSrcSet: `{srcset}`, artwork: [{artwork}] }},")
manifest = '// Generated by scripts/optimize-logos.py. Edit the PNG sources, then regenerate.\n'
manifest += '\n'.join(imports) + '\n\nexport const stationLogos = {\n' + '\n'.join(entries) + '\n};\n'
(ROOT / 'src/data/stationLogos.js').write_text(manifest)
original = sum((SOURCES / f'{name}.png').stat().st_size for name in NAMES)
variants = {size: sum((OUTPUT / f'{name}-{size}.webp').stat().st_size for name in NAMES) for size in SIZES}
print({'original_bytes': original, 'webp_bytes_by_size': variants})
